// Extra languages cover the screens a farmer sees; any other key falls back to English.
const DICTIONARIES: Record<LanguageCode, Partial<Record<TranslationKey, string>>> = {
  en,
  hi,
  kn,
  ...(EXTRA_UI as Record<Exclude<LanguageCode, 'en' | 'hi' | 'kn'>, Partial<Record<TranslationKey, string>>>),
};

export type Translate = (key: TranslationKey, vars?: Record<string, string | number>) => string;

/** Looks up a dynamic key (e.g. field or flag labels); falls back to the key itself. */
export function hasKey(key: string): key is TranslationKey {
  return key in en;
}

export function getTranslator(language: LanguageCode): Translate {
  const dict = DICTIONARIES[language] ?? en;
  return (key, vars) => {
    let text = dict[key] ?? en[key];
    if (vars) {
      for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
    }
    return text;
  };
}
