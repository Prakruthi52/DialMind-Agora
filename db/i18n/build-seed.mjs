// Generates db/seed_i18n.sql from db/i18n/languages.mjs.
// Run: node db/i18n/build-seed.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { LANGS, OPTION_LABELS, SYNONYMS, LEXICON } from './languages.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

const OPTION_QUESTION = {
  paddy: 'crop_affected', ragi: 'crop_affected', maize: 'crop_affected', tur: 'crop_affected',
  cotton: 'crop_affected', groundnut: 'crop_affected', jowar: 'crop_affected', soybean: 'crop_affected',
  hailstorm: 'cause_of_loss', inundation: 'cause_of_loss', landslide: 'cause_of_loss', cloudburst: 'cause_of_loss',
  natural_fire: 'cause_of_loss', unseasonal_rain: 'cause_of_loss', cyclone: 'cause_of_loss', drought: 'cause_of_loss',
  pest_disease: 'cause_of_loss', wild_animal: 'cause_of_loss',
  standing: 'crop_stage', harvested_drying: 'crop_stage',
};

const translations = [];
for (const [lang, L] of Object.entries(LANGS)) {
  for (const [key, text] of Object.entries(L.agent)) translations.push(['agent', key, lang, text]);
  for (const [code, text] of Object.entries(L.q)) translations.push(['question', code, lang, text]);
  for (const [code, text] of Object.entries(L.r)) translations.push(['rule', code, lang, text]);
}
for (const [lang, labels] of Object.entries(OPTION_LABELS)) {
  for (const [value, text] of Object.entries(labels)) {
    translations.push(['option', `${OPTION_QUESTION[value]}:${value}`, lang, text]);
  }
}

const synonyms = [];
for (const [lang, map] of Object.entries(SYNONYMS)) {
  for (const [value, syn] of Object.entries(map)) synonyms.push([OPTION_QUESTION[value], value, lang, syn.toLowerCase()]);
}
// Option labels are always valid synonyms for their own language.
for (const [lang, labels] of Object.entries(OPTION_LABELS)) {
  for (const [value, label] of Object.entries(labels)) {
    const parts = label.split('/').map((s) => s.trim().toLowerCase()).filter(Boolean).join('|');
    const existing = synonyms.find((s) => s[0] === OPTION_QUESTION[value] && s[1] === value && s[2] === lang);
    if (existing) existing[3] = `${existing[3]}|${parts}`;
    else synonyms.push([OPTION_QUESTION[value], value, lang, parts]);
  }
}

const lexicon = [];
for (const [lang, L] of Object.entries(LEXICON)) {
  for (const w of L.yes ?? []) lexicon.push([w.toLowerCase(), 'yes', 1, lang]);
  for (const w of L.no ?? []) lexicon.push([w.toLowerCase(), 'no', 0, lang]);
  for (const [w, v] of Object.entries(L.days ?? {})) lexicon.push([w.toLowerCase(), 'day_offset', v, lang]);
  for (const [w, v] of Object.entries(L.nums ?? {})) lexicon.push([w.toLowerCase(), 'number', v, lang]);
  for (const [w, v] of Object.entries(L.units ?? {})) lexicon.push([w.toLowerCase(), 'area_unit', v, lang]);
  for (const [w, v] of Object.entries(L.pct ?? {})) lexicon.push([w.toLowerCase(), 'percent', v, lang]);
}

const out = [
  '-- GENERATED by db/i18n/build-seed.mjs from db/i18n/languages.mjs. Do not edit by hand.',
  '-- Colloquial translations, per-language synonyms and lexicon for all supported languages.',
  '',
  'INSERT OR REPLACE INTO translations (kind, ref, lang, text) VALUES',
  translations.map((t) => `(${t.map(q).join(', ')})`).join(',\n') + ';',
  '',
  'INSERT OR REPLACE INTO option_synonyms (question_code, value, lang, synonyms) VALUES',
  synonyms.map((s) => `(${s.map(q).join(', ')})`).join(',\n') + ';',
  '',
  'INSERT OR REPLACE INTO lexicon (term, kind, value, lang) VALUES',
  lexicon.map(([t, k, v, l]) => `(${q(t)}, ${q(k)}, ${v}, ${q(l)})`).join(',\n') + ';',
  '',
];
fs.writeFileSync(path.join(here, '..', 'seed_i18n.sql'), out.join('\n'));
console.log(`translations ${translations.length}, synonyms ${synonyms.length}, lexicon ${lexicon.length}`);
